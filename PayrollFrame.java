    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

    int selectedRow = tblPayroll.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this,
                "Please select a payroll record to delete.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to delete this payroll record?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);

    if (confirm == JOptionPane.YES_OPTION) {
        int payrollId = Integer.parseInt(
                tblPayroll.getValueAt(selectedRow, 0).toString());

        if (payrollController.deletePayroll(payrollId)) {
            JOptionPane.showMessageDialog(this,
                    "Payroll record deleted successfully!");
            loadPayroll();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Failed to delete payroll record.");
        }
    }


    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnMarkPendingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMarkPendingActionPerformed


    int selectedRow = tblPayroll.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this,
                "Please select a payroll record first.");
        return;
    }

    int row = tblPayroll.convertRowIndexToModel(selectedRow);

    int payrollId = Integer.parseInt(
            tblPayroll.getModel().getValueAt(row, 0).toString()
    );

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Change this payroll status to Pending?",
            "Confirm",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm == JOptionPane.YES_OPTION) {

        if (payrollController.updatePaymentStatus(payrollId, "Pending")) {

            JOptionPane.showMessageDialog(this,
                    "Payment status changed to Pending!");

            loadPayroll();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Failed to update payment status.");
        }
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnMarkPendingActionPerformed
private void loadPayroll() {
        

    DefaultTableModel model = new DefaultTableModel();

    model.setColumnIdentifiers(new String[]{
        "Payroll ID",
        "Student ID",
        "Period Start",
        "Period End",
        "Amount Due",
        "Payment Status",
        "Payment Date"
    });

    List<Payroll> payrollList =
            payrollController.getAllPayroll();

    for (Payroll p : payrollList) {
        model.addRow(new Object[]{
            p.getPayrollId(),
            p.getStudentId(),
            p.getPeriodStart(),
            p.getPeriodEnd(),
            p.getAmountDue(),
            p.getPaymentStatus(),
            p.getPaymentDate()
        });
    }

    tblPayroll.setModel(model);
}

private void loadStudentCombo() {
    try {
        Connection con = DBConnection.getConnection();

        String sql = "SELECT student_id, first_name, last_name FROM students";

        Statement st = con.createStatement();
        ResultSet rs = st.executeQuery(sql);

        cmbStudent.removeAllItems();

        while (rs.next()) {
            cmbStudent.addItem(
                    rs.getInt("student_id") + " - "
                    + rs.getString("first_name") + " "
                    + rs.getString("last_name"));
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}
