    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
   try {
    if (cmbStudent.getSelectedItem() == null
            || periodStart.getText().trim().isEmpty()
            || periodEnd.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please complete all fields.");
        return;
    }

    Date start = Date.valueOf(periodStart.getText().trim());
    Date end = Date.valueOf(periodEnd.getText().trim());

    if (end.before(start)) {
        JOptionPane.showMessageDialog(this, "Invalid payroll period.");
        return;
    }

    String selected = cmbStudent.getSelectedItem().toString();
    int studentId = Integer.parseInt(selected.split(" - ")[0]);

    Connection con = DBConnection.getConnection();

    String sql = "INSERT INTO payroll "
            + "(student_id, period_start, period_end, amount_due, payment_status) "
            + "SELECT s.student_id, ?, ?, sc.monthly_allowance, 'Pending' "
            + "FROM students s "
            + "JOIN scholarships sc ON s.scholarship_id=sc.scholarship_id "
            + "WHERE s.student_id=?";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setDate(1, start);
    pst.setDate(2, end);
    pst.setInt(3, studentId);

    int result = pst.executeUpdate();
    con.close();

    if (result > 0) {
        JOptionPane.showMessageDialog(this, "Payroll generated successfully!");
        loadPayroll();
    } else {
        JOptionPane.showMessageDialog(this, "Student not found.");
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(this,
            "Please check your dates (YYYY-MM-DD) and selected student.\n"
            + e.getMessage());
}
    }//GEN-LAST:event_btnGenerateActionPerformed

    private void btnMarkPaidActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMarkPaidActionPerformed
 try {
    int row = tblPayroll.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a payroll record.");
        return;
    }

    int id = Integer.parseInt(tblPayroll.getValueAt(row, 0).toString());

    Connection con = DBConnection.getConnection();

    String sql = "UPDATE payroll SET payment_status='Paid', "
            + "payment_date=CURDATE() WHERE payroll_id=?";

    PreparedStatement pst = con.prepareStatement(sql);
    pst.setInt(1, id);

    pst.executeUpdate();
    con.close();

    JOptionPane.showMessageDialog(this, "Payroll marked as paid!");
    loadPayroll();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnMarkPaidActionPerformed

