    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
       try {
    Connection con = DBConnection.getConnection();

    String sql = "SELECT p.payroll_id, s.school_id, "
            + "CONCAT(s.first_name,' ',s.last_name) AS student_name, "
            + "p.period_start, p.period_end, p.amount_due, "
            + "p.payment_status FROM payroll p "
            + "JOIN students s ON p.student_id=s.student_id "
            + "WHERE s.school_id LIKE ? OR s.first_name LIKE ? "
            + "OR s.last_name LIKE ?";

    PreparedStatement pst = con.prepareStatement(sql);

    String search = "%" + txtSearch.getText().trim() + "%";

    pst.setString(1, search);
    pst.setString(2, search);
    pst.setString(3, search);

    ResultSet rs = pst.executeQuery();

    DefaultTableModel model =
            (DefaultTableModel) tblPayroll.getModel();

    model.setRowCount(0);

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("payroll_id"),
            rs.getString("school_id"),
            rs.getString("student_name"),
            rs.getDate("period_start"),
            rs.getDate("period_end"),
            rs.getDouble("amount_due"),
            rs.getString("payment_status")
        });
    }

    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnSearchActionPerformed

