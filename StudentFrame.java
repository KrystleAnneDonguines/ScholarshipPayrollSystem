    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
      try {
    if (txtSchoolId.getText().trim().isEmpty()
            || txtFirstName.getText().trim().isEmpty()
            || txtLastName.getText().trim().isEmpty()
            || txtCourse.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please complete all fields.");
        return;
    }

    Connection con = DBConnection.getConnection();

    String sql = "INSERT INTO students "
            + "(school_id, first_name, last_name, course, year_level, scholarship_id) "
            + "VALUES (?, ?, ?, ?, ?, ?)";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, txtSchoolId.getText().trim());
    pst.setString(2, txtFirstName.getText().trim());
    pst.setString(3, txtLastName.getText().trim());
    pst.setString(4, txtCourse.getText().trim());

    String year = cmbYearLevel.getSelectedItem().toString()
            .replaceAll("[^0-9]", "");
    pst.setInt(5, Integer.parseInt(year));

    String scholarship = cmbScholarship.getSelectedItem().toString();
    int scholarshipId = Integer.parseInt(scholarship.split(" - ")[0]);
    pst.setInt(6, scholarshipId);

    pst.executeUpdate();
    con.close();

    JOptionPane.showMessageDialog(this, "Student added successfully!");
    loadStudents();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    int row = tblStudents.getSelectedRow();

if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please select a student.");
    return;
}

try {
    int modelRow = tblStudents.convertRowIndexToModel(row);
    int id = Integer.parseInt(tblStudents.getModel().getValueAt(modelRow, 0).toString());

    Student s = new Student();
    s.setStudentId(id);
    s.setSchoolId(txtSchoolId.getText());
    s.setFirstName(txtFirstName.getText());
    s.setLastName(txtLastName.getText());
    s.setCourse(txtCourse.getText());

    String year = cmbYearLevel.getSelectedItem().toString();
    s.setYearLevel(Integer.parseInt(year.substring(0, 1)));

    String scholarship = cmbScholarship.getSelectedItem().toString();
    s.setScholarshipId(Integer.parseInt(scholarship.split(" - ")[0]));

    if (studentController.updateStudent(s)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Student updated successfully!");
        loadStudents();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Update failed.");
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please check the fields.");
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
   int row = tblStudents.getSelectedRow();

if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please select a student.");
    return;
}

int modelRow = tblStudents.convertRowIndexToModel(row);
int id = Integer.parseInt(tblStudents.getModel().getValueAt(modelRow, 0).toString());

int confirm = javax.swing.JOptionPane.showConfirmDialog(
    this, "Delete this student?", "Confirm", 
    javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm == javax.swing.JOptionPane.YES_OPTION) {
    if (studentController.deleteStudent(id)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Student deleted!");
        loadStudents();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Delete failed. Check if this student has payroll records.");
    }
}
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
      String search = txtSearch.getText().trim();

javax.swing.table.TableRowSorter<javax.swing.table.TableModel> sorter =
        new javax.swing.table.TableRowSorter<>(tblStudents.getModel());

tblStudents.setRowSorter(sorter);

if (search.isEmpty()) {
    sorter.setRowFilter(null);
} else {
    sorter.setRowFilter(
        javax.swing.RowFilter.regexFilter(
            "(?i)" + java.util.regex.Pattern.quote(search),
            1, 2, 3
        )
    );
}
    }//GEN-LAST:event_btnSearchActionPerformed

