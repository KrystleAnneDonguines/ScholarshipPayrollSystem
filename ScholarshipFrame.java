    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
try {
    if (txtScholarshipName.getText().trim().isEmpty()
            || txtAllowance.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please complete all fields.");
        return;
    }

    double allowance = Double.parseDouble(txtAllowance.getText());

    if (allowance < 0) {
        JOptionPane.showMessageDialog(this, "Allowance cannot be negative.");
        return;
    }

    Connection con = DBConnection.getConnection();

    String sql = "INSERT INTO scholarships "
            + "(scholarship_name, monthly_allowance) VALUES (?, ?)";

    PreparedStatement pst = con.prepareStatement(sql);
    pst.setString(1, txtScholarshipName.getText().trim());
    pst.setDouble(2, allowance);

    pst.executeUpdate();
    con.close();

    JOptionPane.showMessageDialog(this, "Scholarship added successfully!");
    loadScholarships();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
   try {
    int row = tblScholarships.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a scholarship.");
        return;
    }

    int id = Integer.parseInt(tblScholarships.getValueAt(row, 0).toString());

    Connection con = DBConnection.getConnection();

    String sql = "UPDATE scholarships SET scholarship_name=?, "
            + "monthly_allowance=? WHERE scholarship_id=?";

    PreparedStatement pst = con.prepareStatement(sql);
    pst.setString(1, txtScholarshipName.getText().trim());
    pst.setDouble(2, Double.parseDouble(txtAllowance.getText()));
    pst.setInt(3, id);

    pst.executeUpdate();
    con.close();

    JOptionPane.showMessageDialog(this, "Scholarship updated successfully!");
    loadScholarships();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
  try {
    int row = tblScholarships.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a scholarship.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Delete this scholarship?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm == JOptionPane.YES_OPTION) {
        int id = Integer.parseInt(tblScholarships.getValueAt(row, 0).toString());

        Connection con = DBConnection.getConnection();

        PreparedStatement pst = con.prepareStatement(
                "DELETE FROM scholarships WHERE scholarship_id=?");

        pst.setInt(1, id);
        pst.executeUpdate();
        con.close();

        JOptionPane.showMessageDialog(this, "Scholarship deleted!");
        loadScholarships();
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(this,
            "Cannot delete this scholarship if it is assigned to students.\n"
            + e.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

