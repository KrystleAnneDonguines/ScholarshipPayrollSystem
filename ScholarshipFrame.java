private void highlightScholarship() {

    String search = txtSearch.getText().trim().toLowerCase();

    if (search.isEmpty()) {
        tblScholarships.clearSelection();
        return;
    }

    javax.swing.table.TableModel model =
            tblScholarships.getModel();

    boolean found = false;

    for (int row = 0; row < model.getRowCount(); row++) {

        for (int col = 0; col < model.getColumnCount(); col++) {

            Object value = model.getValueAt(row, col);

            if (value != null &&
                value.toString().toLowerCase().contains(search)) {

                int viewRow =
                    tblScholarships.convertRowIndexToView(row);

                if (viewRow >= 0) {
                    tblScholarships.setRowSelectionInterval(
                        viewRow, viewRow
                    );

                    tblScholarships.scrollRectToVisible(
                        tblScholarships.getCellRect(
                            viewRow, 0, true
                        )
                    );

                    found = true;
                    break;
                }
            }
        }

        if (found) {
            break;
        }
    }

    if (!found) {
        tblScholarships.clearSelection();

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Scholarship not found!"
        );
    }
}

